/** その国の解説を取り出す。無ければ null */
function guideFor(country){
  return (typeof GUIDE === "object" && GUIDE[country]) || null;
}

/** 国コードから国旗の絵文字を作る（対応していない端末では JP のように出る） */
function flagOf(cc){
  if (!cc || cc.length !== 2) return "";
  const A = 0x1F1E6, Z = "A".charCodeAt(0);
  return String.fromCodePoint(A + cc.charCodeAt(0) - Z, A + cc.charCodeAt(1) - Z);
}

/* ============================================================
 * 正解発表の画面に出す
 * ============================================================ */
const Guide = (() => {
  const KEY = "gg_guide_open";
  const ROWS = [
    ["drive", "走行"],
    ["sign",  "文字・標識"],
    ["land",  "景色・植生"],
    ["build", "建物・街並み"],
    ["tip",   "決め手"]
  ];

  function isOpen(){
    try { return localStorage.getItem(KEY) !== "off"; } catch(e){ return true; }
  }
  function setOpen(on){
    try { localStorage.setItem(KEY, on ? "on" : "off"); } catch(e){}
  }

  /**
   * 解説を1枚ぶん描く。
   * @param base "res-guide" か "mres-guide"
   * @param country 地点の国名。解説が無ければカードごと隠す
   */
  function render(base, country){
    const box = $(base);
    if (!box) return;
    const g = guideFor(country);
    if (!g){ box.hidden = true; return; }

    const flag = flagOf(g.cc);
    $(base + "-title").textContent = (flag ? flag + " " : "") + country + "の見分け方";

    const body = $(base + "-body");
    body.textContent = "";
    ROWS.forEach(([key, label]) => {
      let v = g[key];
      if (!v) return;                       // 分からない項目は行ごと出さない
      if (key === "drive") v = v + "側通行";
      const dt = document.createElement("dt");
      dt.textContent = label;
      const dd = document.createElement("dd");
      dd.textContent = v;
      if (key === "tip") dd.className = "guide-tip";
      body.appendChild(dt);
      body.appendChild(dd);
    });

    box.hidden = false;
    apply(base, isOpen());
  }

  function apply(base, open){
    const head = $(base + "-head"), body = $(base + "-body");
    if (!head || !body) return;
    head.setAttribute("aria-expanded", open ? "true" : "false");
    head.classList.toggle("closed", !open);
    body.hidden = !open;
  }

  /** 開閉はソロと対戦で共通にする（片方で閉じたらもう片方も閉じている） */
  function init(){
    ["res-guide", "mres-guide"].forEach(base => {
      const head = $(base + "-head");
      if (!head) return;
      head.addEventListener("click", () => {
        const open = !isOpen();
        setOpen(open);
        apply("res-guide", open);
        apply("mres-guide", open);
      });
    });
  }

  return { init, render };
})();
